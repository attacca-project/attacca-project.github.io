/*!
 * stage-carousel.js — long-horizon "skill hand-off" player for the Attacca project page.
 *
 * One carousel per chain (DPX / CCFW / WLO), one slide per policy stage. Stage k's clip ends on the
 * observation it hands over (frame 0 of stage k+1, with stage k's goal inset, no map, no chip, held
 * 0.6 s) and stage k+1's clip opens on that same frame (its own goal inset, map and chip, held 0.6 s).
 * So the automatic advance is a cut by default: the world pixels stay identical and only the goal
 * inset changes (and the new stage's chip and map appear).
 *
 * Behaviour
 *  - muted + playsinline autoplay while the player is on screen, the browser tab is visible and the
 *    chain's tab is selected; paused otherwise (and when the viewer presses pause);
 *  - at the end of a stage the next stage starts at once. The transition is set by data-advance on
 *    .stage-carousel (default "cut"):
 *      cut   – instant switch between two identical frames (the hand-off frame). If stage k+1 has no
 *              decoded frame yet, stage k's last frame stays on screen until it has one (at most
 *              CUT_WAIT_MS), so the cut never shows an empty player;
 *      fade  – ADVANCE_FADE_MS crossfade from stage k's last frame into stage k+1;
 *      slide – SLIDE_MS horizontal slide.
 *    A page URL with ?advance=cut|fade|slide overrides the attribute, to compare the options;
 *  - after the last stage: hold HOLD_MS, then a LOOP_FADE_MS crossfade back to stage 1;
 *  - arrows, stepper thumbnails and the keyboard (Left/Right) jump to a stage and continue autoplay:
 *    a slide to an adjacent stage, a NAV_FADE_MS crossfade for any other jump (wrap-around, a stage
 *    further away, or restarting the current one), so no transition sweeps across several stages;
 *  - the next clip is preloaded (preload="auto") while the current one plays; every clip's poster is
 *    its own first frame, and is also painted under the video (img.sc-under) while the clip is at its
 *    start, so a moment without a video frame never shows the empty player;
 *  - prefers-reduced-motion: every transition is an instant switch.
 *
 * Playback robustness: every play() carries a token; a rejection that belongs to a superseded play()
 * (a jump, a pause, a restart of the same clip) is ignored, an AbortError of the current play() is
 * retried, and a pause that does not come from the component is shown as a viewer pause (play button).
 *
 * Markup contract (generated by site_build_v5/tools/build_site_v5.py):
 *   [data-lh-tabs] [role=tab][aria-controls=<panel id>]         chain tabs (optional)
 *   .stage-carousel#<panel id>[data-advance=cut|fade|slide][data-rate=<playbackRate, default 1>]
 *     .sc-viewport > .sc-track > .sc-slide > video.sc-video   (one slide per stage)
 *     .sc-viewport > button.sc-prev / button.sc-next / button.sc-playpause
 *     .sc-caption  .sc-count / .sc-name / .sc-note
 *     .sc-stepper  button.sc-step[data-index][data-title][data-note]
 *                    img.sc-step-img[data-alt-src][data-switch-t] ; .sc-step-bar > i
 *
 * No dependencies. License: MIT (same terms as the page source).
 */
(function () {
  'use strict';

  var SLIDE_MS = 380;         // slide duration; must match --sc-slide-ms in stage-carousel.css
  var ADVANCE_FADE_MS = 180;  // data-advance="fade"
  var NAV_FADE_MS = 260;      // viewer jumps that are not to an adjacent stage
  var LOOP_FADE_MS = 450;     // last stage -> stage 1
  var HOLD_MS = 2000;         // pause on the last stage before returning to stage 1
  var MAX_PLAY_RETRIES = 3;   // AbortError of the current play() (e.g. an interrupted load)
  var CUT_WAIT_MS = 2500;     // automatic cut: longest wait for the next clip's first frame
  var REWIND_DELAY_MS = 300;  // rewind of the clips left: earliest, after the switch ...
  var REWIND_WAIT_MS = 1000;  // ... and latest, if the new clip has not presented a frame by then
  // The poster underlay stands in for the clip's frame while currentTime is below this (stage 2+ hold the
  // hand-off frame for 0.6 s; stage 1 starts moving at once, so its underlay only covers the start).
  var UNDERLAY_S = 0.5;
  var UNDERLAY_FIRST_S = 0.15;
  var MODES = { cut: true, fade: true, slide: true };

  var mqReduce = window.matchMedia ? window.matchMedia('(prefers-reduced-motion: reduce)') : null;
  function reducedMotion() { return !!(mqReduce && mqReduce.matches); }

  var urlAdvance = (function () {
    try {
      var m = /[?&]advance=(cut|fade|slide)(?:&|$)/.exec(window.location.search || '');
      return m ? m[1] : null;
    } catch (e) { return null; }
  })();

  var carousels = [];

  function StageCarousel(root) {
    this.root = root;
    this.viewport = root.querySelector('.sc-viewport');
    this.track = root.querySelector('.sc-track');
    this.slides = Array.prototype.slice.call(root.querySelectorAll('.sc-slide'));
    this.videos = this.slides.map(function (s) { return s.querySelector('video'); });
    this.steps = Array.prototype.slice.call(root.querySelectorAll('.sc-step'));
    this.prevBtn = root.querySelector('.sc-prev');
    this.nextBtn = root.querySelector('.sc-next');
    this.playBtn = root.querySelector('.sc-playpause');
    this.countEl = root.querySelector('.sc-count');
    this.nameEl = root.querySelector('.sc-name');
    this.noteEl = root.querySelector('.sc-note');
    this.n = this.slides.length;
    var attr = root.getAttribute('data-advance');
    this.advanceMode = urlAdvance || (MODES[attr] ? attr : 'cut');
    this.index = 0;
    this.active = !root.hidden;
    this.inView = false;
    this.nearView = false;
    this.userPaused = false;
    this.state = 'ready';   // ready | sliding | playing | paused | holding | waiting (cut held for data)
    this.playToken = 0;     // identifies the current play() request; bumped whenever it is superseded
    this.playRetries = 0;
    this.slideTimer = null;
    this.holdTimer = null;
    this.waitCancel = null;   // cancels a pending automatic cut (state 'waiting')
    this.fadeEl = null;
    this.fadeTimer = null;
    this.raf = 0;
    this.leftAt = this.videos.map(function () { return false; });   // clips left and not yet rewound
    this.rewindGen = 0;       // identifies the pending rewind of those clips; bumped by every navigation
    this.unders = [];         // per clip: its poster underlay (img.sc-under) or null
    this.underOn = this.videos.map(function () { return true; });   // underlay shown (clip at its start)
    // Playback rate of every clip (data-rate on .stage-carousel, e.g. "0.7"); 1 when absent or invalid.
    var rate = parseFloat(root.getAttribute('data-rate'));
    this.rate = (isFinite(rate) && rate >= 0.25 && rate <= 4) ? rate : 1;
    this.init();
  }

  // Applied on init and again on loadedmetadata / play, so the rate survives load() (which resets
  // playbackRate to defaultPlaybackRate) and any browser that resets it on a new source.
  StageCarousel.prototype.applyRate = function (v) {
    try {
      if (v.defaultPlaybackRate !== this.rate) v.defaultPlaybackRate = this.rate;
      if (v.playbackRate !== this.rate) v.playbackRate = this.rate;
    } catch (e) { /* ignore */ }
  };

  StageCarousel.prototype.init = function () {
    var self = this;
    this.videos.forEach(function (v, i) {
      self.applyRate(v);
      v.addEventListener('loadedmetadata', function () { self.applyRate(v); });
      v.addEventListener('play', function () { self.applyRate(v); });
      v.removeAttribute('controls');        // controls are only a no-JS fallback
      v.removeAttribute('autoplay');
      v.muted = true;
      v.defaultMuted = true;
      v.playsInline = true;
      v.setAttribute('playsinline', '');
      v.addEventListener('ended', function () { self.onEnded(i); });
      v.addEventListener('pause', function () { self.onVideoPause(i); });
      v.addEventListener('error', function () {
        if (window.console) console.warn('stage-carousel: cannot load', v.currentSrc || v.getAttribute('src'));
      });
      // Poster underlay: when the video layer has no frame for a moment (a clip that has played before,
      // rewound while off screen, re-entering at a cut), the viewer sees its first frame, not the
      // empty player. decoding=sync: never painted without its pixels.
      var poster = v.getAttribute('poster');
      var under = null;
      if (poster) {
        under = document.createElement('img');
        under.className = 'sc-under';
        under.alt = '';
        under.setAttribute('aria-hidden', 'true');
        under.setAttribute('decoding', 'sync');
        under.setAttribute('loading', 'eager');
        under.draggable = false;
        under.src = poster;
        v.parentNode.insertBefore(under, v);
      }
      self.unders.push(under);
    });
    if (this.prevBtn) this.prevBtn.addEventListener('click', function () { self.navigate(self.index - 1); });
    if (this.nextBtn) this.nextBtn.addEventListener('click', function () { self.navigate(self.index + 1); });
    if (this.playBtn) this.playBtn.addEventListener('click', function () { self.togglePlay(); });
    this.steps.forEach(function (b) {
      b.addEventListener('click', function () { self.navigate(parseInt(b.getAttribute('data-index'), 10)); });
    });
    this.root.addEventListener('keydown', function (e) { self.onKey(e, true); });

    if ('IntersectionObserver' in window) {
      new IntersectionObserver(function (entries) {
        entries.forEach(function (en) { self.inView = en.isIntersecting && en.intersectionRatio >= 0.35; });
        self.refresh();
      }, { threshold: [0, 0.35, 0.6, 1] }).observe(this.viewport);
      new IntersectionObserver(function (entries) {
        entries.forEach(function (en) { self.nearView = en.isIntersecting; });
        if (self.nearView && self.active) self.preloadAround(self.index);
      }, { rootMargin: '600px 0px' }).observe(this.viewport);
    } else {
      this.inView = this.nearView = true;
    }
    this.jump(0);
    this.updatePlayButton();
  };

  StageCarousel.prototype.canPlay = function () {
    return this.active && this.inView && !document.hidden && !this.userPaused;
  };

  // Pause a clip on the component's own behalf. Each such pause() queues one 'pause' event, which the
  // 'pause' listener must ignore; several can be queued at once (two quick clicks), hence a counter.
  StageCarousel.prototype.pauseVideo = function (v) {
    if (v && !v.paused) {
      v.__scOwnPauses = (v.__scOwnPauses || 0) + 1;
      v.pause();
    }
  };

  // Stop the active clip and invalidate its pending play() (its AbortError is then ignored).
  StageCarousel.prototype.halt = function () {
    this.playToken++;
    this.stopTick();
    this.pauseVideo(this.videos[this.index]);
  };

  // ---- navigation -------------------------------------------------------------------------------

  StageCarousel.prototype.navigate = function (i) {
    // Viewer-initiated jump: continue autoplay from the chosen stage.
    this.userPaused = false;
    var adjacent = (i === this.index + 1 || i === this.index - 1) && i >= 0 && i < this.n;
    this.goTo(i, adjacent ? 'slide' : 'fade', NAV_FADE_MS);
  };

  StageCarousel.prototype.jump = function (i) { this.goTo(i, 'cut'); };

  // mode: 'cut' | 'fade' | 'slide'; fadeMs only for 'fade'.
  StageCarousel.prototype.goTo = function (i, mode, fadeMs) {
    var self = this;
    i = ((i % this.n) + this.n) % this.n;
    var prev = this.index;
    if (!MODES[mode] || reducedMotion()) mode = 'cut';
    if (mode === 'slide' && i === prev) mode = 'fade';
    this.clearTimers();
    this.playToken++;                       // any pending play() is superseded from here on
    this.playRetries = 0;
    this.rewindGen++;                       // so is any pending rewind: prev may still be on screen

    // A crossfade freezes the frame on screen now (before the clip is paused or rewound).
    if (mode === 'fade') this.startFade(this.videos[prev], fadeMs || NAV_FADE_MS);
    else this.clearFade();

    if (i !== prev) { this.pauseVideo(this.videos[prev]); this.leftAt[prev] = true; }
    this.index = i;

    var v = this.videos[i];
    this.pauseVideo(v);
    this.leftAt[i] = false;
    try { if (v.currentTime !== 0) v.currentTime = 0; } catch (e) { /* not seekable yet */ }
    this.setUnderlay(i, true);

    this.updateUI();
    this.preloadAround(i);

    var animate = mode === 'slide';
    this.setTrack(animate);
    this.state = 'sliding';
    var done = function () {
      self.slideTimer = null;
      self.state = 'ready';
      self.refresh();
      self.rewindLeft();
    };
    if (animate) this.slideTimer = setTimeout(done, SLIDE_MS + 30);
    else done();
  };

  // Rewind the clips we left, so that coming back to one shows its first frame. Never in the task that
  // moves the track: a paused clip's new frame reaches the compositor before the new track position
  // does (which can take several frames), so the left slide would show its own first frame at the old
  // position. Waits REWIND_DELAY_MS and for the active clip's first presented frame (at most
  // REWIND_WAIT_MS), then two animation frames; any navigation in between cancels it, and the next
  // navigation's rewind takes over.
  StageCarousel.prototype.rewindLeft = function () {
    var self = this;
    var gen = ++this.rewindGen;
    if (!this.leftAt.some(function (left) { return left; })) return;
    var v = this.videos[this.index];
    var shown = !v.requestVideoFrameCallback, waited = false, fired = false, vfc = 0;
    var rewind = function () {
      if (gen !== self.rewindGen) return;
      self.leftAt.forEach(function (left, j) {
        if (!left || j === self.index) return;
        self.leftAt[j] = false;
        try { if (self.videos[j].currentTime !== 0) self.videos[j].currentTime = 0; } catch (e) { /* ignore */ }
        self.setUnderlay(j, true);
      });
    };
    var go = function () {
      if (fired || !shown || !waited || gen !== self.rewindGen) return;
      fired = true;
      window.requestAnimationFrame(function () { window.requestAnimationFrame(rewind); });
    };
    if (!shown) vfc = v.requestVideoFrameCallback(function () { vfc = 0; shown = true; go(); });
    setTimeout(function () { waited = true; go(); }, REWIND_DELAY_MS);
    setTimeout(function () {
      if (vfc && v.cancelVideoFrameCallback) v.cancelVideoFrameCallback(vfc);
      shown = true;
      go();
    }, REWIND_WAIT_MS);
  };

  // Show clip j's poster underlay while the clip is at its start; hide it once the clip has played past
  // the frames the poster stands for.
  StageCarousel.prototype.setUnderlay = function (j, on) {
    if (this.underOn[j] === on) return;
    this.underOn[j] = on;
    this.slides[j].classList.toggle('sc-past-start', !on);
  };

  StageCarousel.prototype.setTrack = function (animate) {
    var t = this.track;
    if (!animate) t.style.transition = 'none';
    t.style.transform = 'translate3d(' + (-100 * this.index) + '%,0,0)';
    if (!animate) {
      void t.offsetWidth;                 // commit the jump before re-enabling the transition
      t.style.transition = '';
    }
  };

  // Crossfade: a still of the outgoing clip's current frame (or its poster) over the viewport, faded out.
  StageCarousel.prototype.startFade = function (v, ms) {
    this.clearFade();
    var el = null;
    if (v && v.readyState >= 2 && v.videoWidth) {
      try {
        el = document.createElement('canvas');
        el.width = v.videoWidth;
        el.height = v.videoHeight;
        el.getContext('2d').drawImage(v, 0, 0, el.width, el.height);
      } catch (e) { el = null; }
    }
    // the poster is the clip's first frame, so it only stands in for a clip that is still at its start
    if (!el && v && v.getAttribute('poster') && v.currentTime === 0) {
      el = document.createElement('img');
      el.alt = '';
      el.src = v.getAttribute('poster');
    }
    if (!el) return;
    var self = this;
    el.className = 'sc-fade';
    el.setAttribute('aria-hidden', 'true');
    el.style.transitionDuration = ms + 'ms';
    this.viewport.insertBefore(el, this.track.nextSibling);   // above the clips, below the buttons
    void el.offsetWidth;                                       // start from opacity 1
    el.classList.add('is-out');
    this.fadeEl = el;
    this.fadeTimer = setTimeout(function () { self.clearFade(); }, ms + 80);
  };

  StageCarousel.prototype.clearFade = function () {
    clearTimeout(this.fadeTimer); this.fadeTimer = null;
    if (this.fadeEl && this.fadeEl.parentNode) this.fadeEl.parentNode.removeChild(this.fadeEl);
    this.fadeEl = null;
  };

  StageCarousel.prototype.onEnded = function (i) {
    if (i !== this.index) return;
    // 'paused' is accepted too, so a stage can never end without advancing while the viewer has not paused.
    if (!(this.state === 'playing' || (this.state === 'paused' && !this.userPaused))) return;
    this.playToken++;
    this.stopTick();
    this.paintProgress(1);
    if (i < this.n - 1) {
      this.advance(i + 1);
    } else {
      this.state = 'holding';
      this.startHold();
    }
  };

  // Automatic advance to stage j. A cut waits until stage j's clip has a decoded frame (readyState >= 2),
  // keeping stage k's last frame (the same world frame) on screen, so the switch never shows a blank player.
  StageCarousel.prototype.advance = function (j) {
    var self = this;
    var mode = this.advanceMode;
    var v = this.videos[j];
    if (mode !== 'cut' || reducedMotion() || v.readyState >= 2) {
      this.goTo(j, mode, ADVANCE_FADE_MS);
      return;
    }
    this.state = 'waiting';
    if (v.preload !== 'auto') v.preload = 'auto';
    if (v.readyState === 0 && v.networkState !== 2 /* NETWORK_LOADING */) { try { v.load(); } catch (e) { /* ignore */ } }
    var timer = null;
    var done = false;
    var finish = function () {
      if (done) return;
      done = true;
      v.removeEventListener('loadeddata', finish);
      clearTimeout(timer);
      self.waitCancel = null;
      if (self.state === 'waiting') self.goTo(j, 'cut');
    };
    v.addEventListener('loadeddata', finish);
    timer = setTimeout(finish, CUT_WAIT_MS);
    // clearTimers() (any navigation) or a pause/scroll-away while waiting: stop waiting
    this.waitCancel = function (switchNow) {
      if (done) return;
      done = true;
      v.removeEventListener('loadeddata', finish);
      clearTimeout(timer);
      self.waitCancel = null;
      if (switchNow && self.state === 'waiting') self.goTo(j, 'cut');
    };
  };

  StageCarousel.prototype.startHold = function () {
    var self = this;
    clearTimeout(this.holdTimer);
    this.holdTimer = setTimeout(function () {
      self.holdTimer = null;
      if (self.canPlay()) self.goTo(0, 'fade', LOOP_FADE_MS);
    }, HOLD_MS);
  };

  StageCarousel.prototype.clearTimers = function () {
    if (this.waitCancel) this.waitCancel(false);
    clearTimeout(this.slideTimer); this.slideTimer = null;
    clearTimeout(this.holdTimer); this.holdTimer = null;
    this.stopTick();
  };

  // ---- playback ---------------------------------------------------------------------------------

  StageCarousel.prototype.refresh = function () {
    if (this.state === 'sliding') { this.updatePlayButton(); return; }   // `done` will call back
    if (this.state === 'waiting') {
      // an automatic cut is waiting for the next clip's first frame; if playback may not go on, switch now
      // (the next stage then waits, paused, on its first frame)
      if (!this.canPlay() && this.waitCancel) this.waitCancel(true);
      this.updatePlayButton();
      return;
    }
    if (this.canPlay()) {
      if (this.state === 'holding') {
        if (!this.holdTimer) this.startHold();
      } else if (this.state !== 'playing') {
        this.playActive();
      }
    } else {
      clearTimeout(this.holdTimer); this.holdTimer = null;
      if (this.state === 'playing') this.state = 'paused';
      this.halt();
    }
    this.updatePlayButton();
  };

  StageCarousel.prototype.playActive = function () {
    var self = this;
    var v = this.videos[this.index];
    var tok = ++this.playToken;
    this.state = 'playing';
    this.startTick();
    var p;
    try { p = v.play(); } catch (e) { p = null; }
    if (!p || typeof p.then !== 'function') return;
    p.then(function () {
      if (tok === self.playToken) self.playRetries = 0;
    }, function (err) {
      // A rejection of a superseded play() (jump, pause, restart of the same clip) says nothing about now.
      if (tok !== self.playToken || self.state !== 'playing') return;
      var name = err && err.name;
      if (name === 'AbortError' && self.playRetries < MAX_PLAY_RETRIES) {
        // The current play() was interrupted by something else (e.g. a load()); ask again.
        self.playRetries++;
        setTimeout(function () {
          if (tok === self.playToken && self.state === 'playing' && self.canPlay() && v.paused && !v.ended) {
            self.state = 'ready';
            self.playActive();
          }
        }, 60);
        return;
      }
      self.stopTick();
      self.state = 'paused';
      if (name === 'NotAllowedError') self.userPaused = true;   // autoplay refused: wait for a click
      self.updatePlayButton();
    });
  };

  // A pause the component did not ask for (browser media controls, picture-in-picture, ...): show it
  // as a viewer pause instead of believing the clip still plays.
  StageCarousel.prototype.onVideoPause = function (i) {
    var v = this.videos[i];
    if (v.__scOwnPauses > 0) { v.__scOwnPauses--; return; }
    if (!v.paused || v.ended) return;          // already superseded by a later play(), or the natural end
    if (i !== this.index || this.state !== 'playing') return;
    this.playToken++;
    this.stopTick();
    this.state = 'paused';
    this.userPaused = true;
    this.updatePlayButton();
  };

  StageCarousel.prototype.togglePlay = function () {
    this.userPaused = !this.userPaused;
    this.refresh();
  };

  StageCarousel.prototype.setActive = function (on) {
    this.active = !!on;
    this.root.hidden = !on;
    if (on) {
      this.userPaused = false;
      this.jump(0);
      if (this.nearView) this.preloadAround(0);
    } else {
      this.clearTimers();
      this.clearFade();
      this.halt();
      // back to stage 1 while the panel is hidden, so selecting the tab again never shows a stale frame first
      this.goTo(0, 'cut');
      this.state = 'ready';
    }
    this.refresh();
  };

  // Keep the active clip and the next one (wrapping to stage 1 after the last) buffered.
  StageCarousel.prototype.preloadAround = function (i) {
    if (!this.active || !this.nearView) return;
    var n = this.n, self = this;
    [i, (i + 1) % n].forEach(function (j) {
      var u = self.unders[j];
      if (u && !u.__scDecoded && u.decode) {
        u.__scDecoded = true;
        u.decode().catch(function () { u.__scDecoded = false; });
      }
      var v = self.videos[j];
      if (v.preload !== 'auto') {
        v.preload = 'auto';
        // never load() the clip that is being played: that would abort its play()
        var playingThis = j === self.index && self.state === 'playing';
        if (!playingThis && v.readyState === 0 && v.networkState !== 2 /* NETWORK_LOADING */) v.load();
      }
    });
  };

  // ---- UI ---------------------------------------------------------------------------------------

  StageCarousel.prototype.updateUI = function () {
    var i = this.index, n = this.n, self = this;
    this.slides.forEach(function (s, j) {
      s.setAttribute('aria-hidden', j === i ? 'false' : 'true');
      s.classList.toggle('is-active', j === i);
    });
    this.steps.forEach(function (b, j) {
      if (j === i) b.setAttribute('aria-current', 'step'); else b.removeAttribute('aria-current');
      b.classList.toggle('is-done', j < i);
      var bar = b.querySelector('.sc-step-bar i');
      if (bar) bar.style.transform = 'scaleX(' + (j < i ? 1 : 0) + ')';
      self.setStepGoal(b, j < i ? Infinity : (j > i ? -1 : 0));
    });
    var step = this.steps[i];
    if (step) {
      if (this.countEl) this.countEl.textContent = 'Stage ' + (i + 1) + ' / ' + n;
      if (this.nameEl) this.nameEl.textContent = step.getAttribute('data-title') || '';
      if (this.noteEl) {
        var note = step.getAttribute('data-note') || '';
        this.noteEl.textContent = note;
        this.noteEl.hidden = !note;
      }
    }
  };

  // Thumbnails of stages whose goal image switches mid-stage (WLO portal) follow the video.
  StageCarousel.prototype.setStepGoal = function (b, t) {
    var img = b.querySelector('.sc-step-img[data-alt-src]');
    if (!img) return;
    if (!img.getAttribute('data-main-src')) img.setAttribute('data-main-src', img.getAttribute('src'));
    var useAlt = t >= parseFloat(img.getAttribute('data-switch-t'));
    var want = img.getAttribute(useAlt ? 'data-alt-src' : 'data-main-src');
    if (img.getAttribute('src') !== want) img.setAttribute('src', want);
  };

  StageCarousel.prototype.paintProgress = function (frac) {
    var b = this.steps[this.index];
    var bar = b && b.querySelector('.sc-step-bar i');
    if (bar) bar.style.transform = 'scaleX(' + Math.max(0, Math.min(1, frac)) + ')';
  };

  StageCarousel.prototype.startTick = function () {
    var self = this;
    this.stopTick();
    var tick = function () {
      var v = self.videos[self.index];
      var d = v.duration;
      if (d && isFinite(d)) self.paintProgress(v.currentTime / d);
      if (self.steps[self.index]) self.setStepGoal(self.steps[self.index], v.currentTime);
      if (v.currentTime > (self.index === 0 ? UNDERLAY_FIRST_S : UNDERLAY_S)) self.setUnderlay(self.index, false);
      self.raf = window.requestAnimationFrame(tick);
    };
    this.raf = window.requestAnimationFrame(tick);
  };

  StageCarousel.prototype.stopTick = function () {
    if (this.raf) window.cancelAnimationFrame(this.raf);
    this.raf = 0;
  };

  StageCarousel.prototype.updatePlayButton = function () {
    if (!this.playBtn) return;
    var paused = this.userPaused;
    this.playBtn.classList.toggle('is-paused', paused);
    this.playBtn.setAttribute('aria-label', paused ? 'Play' : 'Pause');
    this.playBtn.setAttribute('title', paused ? 'Play' : 'Pause');
  };

  StageCarousel.prototype.onKey = function (e, fromInside) {
    if (e.defaultPrevented || e.altKey || e.ctrlKey || e.metaKey || e.shiftKey) return;
    if (!this.active) return;
    if (!fromInside && !this.inView) return;
    if (e.key === 'ArrowLeft') { this.navigate(this.index - 1); e.preventDefault(); }
    else if (e.key === 'ArrowRight') { this.navigate(this.index + 1); e.preventDefault(); }
  };

  // ---- chain tabs -------------------------------------------------------------------------------

  function initTabs(list) {
    var tabs = Array.prototype.slice.call(list.querySelectorAll('[role="tab"]'));
    function byPanel(tab) {
      var id = tab.getAttribute('aria-controls');
      for (var k = 0; k < carousels.length; k++) if (carousels[k].root.id === id) return carousels[k];
      return null;
    }
    function select(tab, focus) {
      tabs.forEach(function (t) {
        var on = t === tab;
        t.setAttribute('aria-selected', on ? 'true' : 'false');
        t.setAttribute('tabindex', on ? '0' : '-1');
        if (t.parentNode && t.parentNode.classList) t.parentNode.classList.toggle('is-active', on);
        if (!on) { var c = byPanel(t); if (c && c.active) c.setActive(false); }
      });
      var cur = byPanel(tab);
      if (cur && !cur.active) cur.setActive(true);
      if (focus) tab.focus();
    }
    tabs.forEach(function (t, k) {
      t.addEventListener('click', function (e) { e.preventDefault(); select(t, false); });
      t.addEventListener('keydown', function (e) {
        var to = null;
        if (e.key === 'ArrowRight') to = tabs[(k + 1) % tabs.length];
        else if (e.key === 'ArrowLeft') to = tabs[(k - 1 + tabs.length) % tabs.length];
        else if (e.key === 'Home') to = tabs[0];
        else if (e.key === 'End') to = tabs[tabs.length - 1];
        if (to) { e.preventDefault(); e.stopPropagation(); select(to, true); }
      });
    });
    // Deep link: #<panel id> selects that chain.
    var h = (window.location.hash || '').slice(1);
    var initial = tabs.filter(function (t) { return t.getAttribute('aria-controls') === h; })[0] ||
                  tabs.filter(function (t) { return t.getAttribute('aria-selected') === 'true'; })[0] || tabs[0];
    if (initial) select(initial, false);
  }

  function isTypingTarget(el) {
    if (!el || el === document.body) return false;
    var tag = el.tagName;
    return tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT' || el.isContentEditable ||
           (el.getAttribute && el.getAttribute('role') === 'tab');
  }

  function boot() {
    var roots = document.querySelectorAll('.stage-carousel');
    for (var k = 0; k < roots.length; k++) carousels.push(new StageCarousel(roots[k]));
    var lists = document.querySelectorAll('[data-lh-tabs]');
    for (var m = 0; m < lists.length; m++) initTabs(lists[m]);

    document.addEventListener('visibilitychange', function () {
      carousels.forEach(function (c) { c.refresh(); });
    });
    // Left/Right also work without focusing the player, while the active player is on screen.
    document.addEventListener('keydown', function (e) {
      var ae = document.activeElement;
      if (isTypingTarget(ae)) return;
      for (var k = 0; k < carousels.length; k++) {
        var c = carousels[k];
        if (ae && c.root.contains(ae)) return;          // handled by the component's own listener
      }
      carousels.forEach(function (c) { c.onKey(e, false); });
    });
    if (mqReduce && mqReduce.addEventListener) {
      mqReduce.addEventListener('change', function () { carousels.forEach(function (c) { c.clearFade(); c.setTrack(false); }); });
    }
    window.StageCarousels = carousels;   // exposed for debugging / tests
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot);
  else boot();
})();
